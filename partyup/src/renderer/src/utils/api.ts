const invoke = (channel: string, ...args: any[]) => {
  if (window.electron?.ipc?.invoke) {
    return window.electron.ipc.invoke(channel, ...args);
  }
  console.warn(`IPC not available for channel: ${channel}`);
  return Promise.resolve(null);
};

